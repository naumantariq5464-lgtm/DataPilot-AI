def load(csv_str: str) -> pd.DataFrame:
    return pd.read_csv(io.StringIO(csv_str))


# ── Employee Dataset Tests ────────────────────────────────────────────────────

class TestEmployeeAnalysis:

    def setup_method(self):
        self.df = load(EMPLOYEE_CSV)

    def test_total_employees(self):
        assert len(self.df) == 10

    def test_total_projects(self):
        total = int(self.df["Projects_Completed"].sum())
        assert total == 144

    def test_average_projects(self):
        avg = round(self.df["Projects_Completed"].mean(), 2)
        assert avg == 14.40

    def test_max_projects_employee(self):
        idx = self.df["Projects_Completed"].idxmax()
        best = self.df.loc[idx, "Employee"]
        assert best == "Ayesha"
        assert int(self.df.loc[idx, "Projects_Completed"]) == 22

    def test_ranking_order(self):
        ranked = self.df.sort_values("Projects_Completed", ascending=False)
        names = ranked["Employee"].tolist()
        assert names[0] == "Ayesha"
        assert names[1] == "Nauman"
        assert names[2] == "Sara"
        assert names[-1] == "Zain"

    def test_total_salary(self):
        total = int(self.df["Salary"].sum())
        assert total == 685000

    def test_average_salary(self):
        avg = round(self.df["Salary"].mean(), 2)
        assert avg == 68500.0

    def test_highest_salary(self):
        max_sal = int(self.df["Salary"].max())
        assert max_sal == 95000
        emp = self.df.loc[self.df["Salary"].idxmax(), "Employee"]
        assert emp == "Ayesha"

    def test_department_counts(self):
        counts = self.df.groupby("Department").size().to_dict()
        assert counts["Engineering"] == 3
        assert counts["Sales"] == 3
        assert counts["Marketing"] == 2
        assert counts["HR"] == 2

    def test_dept_avg_salary(self):
        avg = self.df.groupby("Department")["Salary"].mean()
        eng_avg = round(float(avg["Engineering"]), 2)
        assert eng_avg == round((95000 + 88000 + 82000) / 3, 2)


# ── Sales Dataset Tests ───────────────────────────────────────────────────────

class TestSalesAnalysis:

    def setup_method(self):
        self.df = load(SALES_CSV)

    def test_total_revenue(self):
        total = int(self.df["Revenue"].sum())
        assert total == 1675000

    def test_total_quantity(self):
        total = int(self.df["Quantity"].sum())
        assert total == 615

    def test_best_selling_product_by_quantity(self):
        by_qty = self.df.groupby("Product")["Quantity"].sum()
        best = by_qty.idxmax()
        assert best == "Phone"
        assert int(by_qty[best]) == 360

    def test_best_selling_product_by_revenue(self):
        by_rev = self.df.groupby("Product")["Revenue"].sum()
        best = by_rev.idxmax()
        assert best == "Laptop"  # 250000+200000+175000 = 625000

    def test_city_with_highest_revenue(self):
        by_city = self.df.groupby("City")["Revenue"].sum()
        best = by_city.idxmax()
        assert best == "Karachi"  # 250000+225000+75000+225000 = 775000

    def test_revenue_per_city(self):
        by_city = self.df.groupby("City")["Revenue"].sum()
        assert int(by_city["Karachi"]) == 775000
        assert int(by_city["Lahore"]) == 500000
        assert int(by_city["Islamabad"]) == 400000


