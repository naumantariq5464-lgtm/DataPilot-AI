# ── Orders / Date Tests ───────────────────────────────────────────────────────

class TestOrdersAnalysis:

    def setup_method(self):
        self.df = load(ORDERS_CSV)
        self.df["Date"] = pd.to_datetime(self.df["Date"])
        self.df["Revenue"] = self.df["Qty"] * self.df["Price"]

    def test_total_orders(self):
        assert len(self.df) == 10

    def test_completed_orders(self):
        completed = self.df[self.df["Status"] == "Completed"]
        assert len(completed) == 8

    def test_total_revenue_completed(self):
        completed = self.df[self.df["Status"] == "Completed"]
        total = int((completed["Qty"] * completed["Price"]).sum())
        # 1×85000=85000, 2×15000=30000, 2×85000=170000, 1×15000=15000,
        # 3×5000=15000, 1×85000=85000, 4×15000=60000, 2×25000=50000
        assert total == 510000

    def test_monthly_order_count(self):
        monthly = self.df.groupby(self.df["Date"].dt.month).size()
        assert monthly[1] == 3  # Jan: orders 1,2,3
        assert monthly[2] == 3  # Feb: orders 4,5,6
        assert monthly[3] == 3  # Mar: orders 7,8,9
        assert monthly[4] == 1  # Apr: order 10


# ── Statistics Sanitisation Verification ─────────────────────────────────────

class TestStatsSanitisationEdgeCases:
    """Verify sanitisation handles all problematic types."""

    def test_ranking_as_string_readable(self):
        """Verify the string format produced by _list_to_string is human-readable."""
        from app.services.sandbox_service import _list_to_string
        items = [
            {"name": "Ayesha", "value": 22},
            {"name": "Nauman", "value": 20},
            {"name": "Sara", "value": 18},
        ]
        result = _list_to_string(items)
        assert "1. Ayesha — 22" in result
        assert "2. Nauman — 20" in result
        assert "3. Sara — 18" in result
        assert "[object Object]" not in result

    def test_object_not_in_sanitised_output(self):
        """No statistics value should ever produce [object Object]."""
        from app.services.sandbox_service import _sanitize_statistics
        stats = {
            "number": 42,
            "string": "hello",
            "array": [1, 2, 3],
            "obj_array": [{"name": "X", "value": 10}],
            "nested_dict": {"a": 1, "b": 2},
            "none_val": None,
            "nan_val": float("nan"),
            "inf_val": float("inf"),
        }
        result = _sanitize_statistics(stats)
        for key, val in result.items():
            rendered = str(val)
            assert "[object Object]" not in rendered, f"[object Object] found in {key}: {val}"
            assert val is not None

    def test_all_chart_data_numeric(self):
        """Chart parser should produce numeric values, not strings or None."""
        from app.routers.analysis import _parse_charts
        raw = [{
            "type": "bar",
            "title": "Test",
            "x_label": "Cat",
            "y_label": "Val",
            "data": [
                {"name": "A", "value": 100},
                {"name": "B", "count": 200},   # different field name
                {"label": "C", "value": 300},  # different name field
                {"name": "D", "value": None},  # null value
                {"name": "E", "value": float("nan")},  # NaN
            ]
        }]
        charts = _parse_charts(raw)
        assert len(charts) == 1
        values = [item["value"] for item in charts[0].data]
        for v in values:
            assert isinstance(v, float)
            assert math.isfinite(v)  # No NaN or infinity
